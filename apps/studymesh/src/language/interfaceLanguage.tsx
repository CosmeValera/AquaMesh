const getInterfaceTranslation = (
  language: InterfaceLanguageCode,
  key: InterfaceTextKey,
): string => {
  if (language === 'en' || language === 'es') {
    return translations[language][key] || translations.en[key]
  }

  return translationOverrides[language][key] || translations.en[key]
}

interface InterfaceLanguageContextValue {
  language: InterfaceLanguageCode
  setLanguage: (language: InterfaceLanguageCode) => void
  t: (key: InterfaceTextKey) => string
}

const InterfaceLanguageContext =
  React.createContext<InterfaceLanguageContextValue | null>(null)

/**
 * `forceLanguage` pins the whole tree to one language and makes `setLanguage` a
 * no-op. The logged-out surfaces (landing, pricing) are hardcoded English, so
 * the demo pins itself to English too rather than following the browser locale
 * into a half-translated page. A pinned surface must not write the visitor's
 * stored settings either: they never asked for the change.
 */
export const InterfaceLanguageProvider: React.FC<{
  children: React.ReactNode
  forceLanguage?: InterfaceLanguageCode
}> = ({ children, forceLanguage }) => {
  const [storedLanguage, setLanguageState] =
    React.useState<InterfaceLanguageCode>(
      () => readContentLanguageSettings().interfaceLanguage,
    )
  const language = forceLanguage || storedLanguage

  React.useEffect(() => {
    const refresh = () => {
      setLanguageState(readContentLanguageSettings().interfaceLanguage)
    }

    window.addEventListener(CONTENT_LANGUAGE_SETTINGS_CHANGED_EVENT, refresh)
    window.addEventListener('storage', refresh)

    return () => {
      window.removeEventListener(
        CONTENT_LANGUAGE_SETTINGS_CHANGED_EVENT,
        refresh,
      )
      window.removeEventListener('storage', refresh)
    }
  }, [])

  const value = React.useMemo<InterfaceLanguageContextValue>(
    () => ({
      language,
      setLanguage: (nextLanguage) => {
        if (forceLanguage) {
          return
        }

        setLanguageState(nextLanguage)
        saveContentLanguageSettings({
          ...readContentLanguageSettings(),
          interfaceLanguage: nextLanguage,
        })
      },
      t: (key) => getInterfaceTranslation(language, key),
    }),
    [forceLanguage, language],
  )

  return (
    <InterfaceLanguageContext.Provider value={value}>
      {children}
    </InterfaceLanguageContext.Provider>
  )
}

export const useInterfaceText = (): InterfaceLanguageContextValue => {
  const value = React.useContext(InterfaceLanguageContext)
  if (!value) {
    return {
      language: 'en',
      setLanguage: (nextLanguage) => {
        saveContentLanguageSettings({
          ...readContentLanguageSettings(),
          interfaceLanguage: nextLanguage,
        })
      },
      t: (key) => getInterfaceTranslation('en', key),
    }
  }

  return value
}
