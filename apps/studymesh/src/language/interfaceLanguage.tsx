type InterfaceTextKey = keyof typeof translations.en

interface InterfaceLanguageContextValue {
  language: InterfaceLanguageCode
  setLanguage: (language: InterfaceLanguageCode) => void
  t: (key: InterfaceTextKey) => string
}

const InterfaceLanguageContext =
  React.createContext<InterfaceLanguageContextValue | null>(null)

export const InterfaceLanguageProvider: React.FC<{
  children: React.ReactNode
}> = ({ children }) => {
  const [language, setLanguageState] = React.useState<InterfaceLanguageCode>(
    () => readContentLanguageSettings().interfaceLanguage,
  )

  React.useEffect(() => {
    const refresh = () => {
      setLanguageState(readContentLanguageSettings().interfaceLanguage)
    }

    window.addEventListener(CONTENT_LANGUAGE_SETTINGS_CHANGED_EVENT, refresh)
    window.addEventListener('storage', refresh)

    return () => {
      window.removeEventListener(
        CONTENT_LANGUAGE_SETTINGS_CHANGED_EVENT,
        refresh,
      )
      window.removeEventListener('storage', refresh)
    }
  }, [])

  const value = React.useMemo<InterfaceLanguageContextValue>(
    () => ({
      language,
      setLanguage: (nextLanguage) => {
        saveContentLanguageSettings({
          ...readContentLanguageSettings(),
          interfaceLanguage: nextLanguage,
        })
      },
      t: (key) => translations[language][key] || translations.en[key],
    }),
    [language],
  )

  return (
    <InterfaceLanguageContext.Provider value={value}>
      {children}
    </InterfaceLanguageContext.Provider>
  )
}

export const useInterfaceText = (): InterfaceLanguageContextValue => {
  const value = React.useContext(InterfaceLanguageContext)
  if (!value) {
    return {
      language: 'en',
      setLanguage: (nextLanguage) => {
        saveContentLanguageSettings({
          ...readContentLanguageSettings(),
          interfaceLanguage: nextLanguage,
        })
      },
      t: (key) => translations.en[key],
    }
  }

  return value
}
